// Embeds drizzle/*.sql into lib/db/migrations.generated.ts so migrations ship
// inside the production bundle (Hostinger offers no SSH to run CLI tools).
// Run after `pnpm db:generate`.
import { readFileSync, writeFileSync } from 'node:fs';

const journal = JSON.parse(readFileSync('drizzle/meta/_journal.json', 'utf8'));
const out = journal.entries.map((e) => {
  const sql = readFileSync(`drizzle/${e.tag}.sql`, 'utf8');
  const statements = sql
    .split('--> statement-breakpoint')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => (/^CREATE TABLE/i.test(s) ? s.replace(/;?\s*$/, ' DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;') : s));
  return { id: e.tag, statements };
});
writeFileSync(
  'lib/db/migrations.generated.ts',
  `// AUTO-GENERATED by scripts/embed-migrations.mjs — do not edit by hand.\n` +
    `export const MIGRATIONS: { id: string; statements: string[] }[] = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`Embedded ${out.length} migration(s).`);
